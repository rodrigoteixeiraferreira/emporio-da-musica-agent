"""Turn the store's policy manual (PDF) into Markdown, once, at build time.

The manual is short (8 pages), so the agent reads it whole from the system prompt
instead of retrieving chunks. This module only does the PDF -> Markdown step; the
result is versioned at ``data/processed/policies.md`` so a reviewer can read exactly
what the model sees.
"""

from __future__ import annotations

import re
from pathlib import Path

from pypdf import PdfReader

from .config import POLICIES_MD, POLICIES_PDF

_PAGE_HEADER = "Empório da Música Manual de Políticas e Procedimentos"
_PAGE_FOOTER = re.compile(r"^\s*Página \d+\s*$")
_H2 = re.compile(r"^\d+\.\s+\S")          # "4. Política de Trocas" at column 0
_H3 = re.compile(r"^\d+\.\d+\s+\S")       # "4.1 Direito de Arrependimento" at column 0
_COLUMN_GAP = re.compile(r"\S {3,}\S")    # table columns are separated by wide gaps
_LIST_ITEM = re.compile(r"^(•|\d+\.)\s")


def _table_cells(line: str) -> list[str]:
    return [c.strip() for c in re.split(r" {3,}", line.strip()) if c.strip()]


def _render_table(rows: list[list[str]]) -> list[str]:
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    out = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * width]
    out += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return out


def pdf_to_markdown(pdf_path: Path) -> str:
    """Extract the manual and apply light, mechanical formatting (no rewording)."""
    reader = PdfReader(str(pdf_path))
    out: list[str] = []
    table: list[list[str]] = []

    def flush_table() -> None:
        if table:
            out.extend(_render_table(table))
            out.append("")
            table.clear()

    for page_no, page in enumerate(reader.pages, start=1):
        text = page.extract_text(extraction_mode="layout")
        for raw in text.splitlines():
            line = raw.rstrip()
            if not line.strip() or line.strip() == _PAGE_HEADER or _PAGE_FOOTER.match(line):
                continue

            if page_no == 1:  # cover page: keep as a plain block
                out.append(line.strip() + "  ")
                continue

            indented = line.startswith(" ")
            stripped = line.strip()

            if indented and _COLUMN_GAP.search(stripped) and not _LIST_ITEM.match(stripped):
                if not table and out and out[-1]:
                    out.append("")  # Markdown needs a blank line before a table
                table.append(_table_cells(stripped))
                continue
            if table and indented and not _LIST_ITEM.match(stripped):
                # A wrapped cell inside a table (e.g. "... preço de" / "tabela").
                table[-1][-1] = f"{table[-1][-1]} {stripped}".strip()
                continue
            flush_table()

            if not indented and _H3.match(stripped):
                out += ["", "### " + stripped, ""]
            elif not indented and _H2.match(stripped):
                out += ["", "## " + stripped, ""]
            elif _LIST_ITEM.match(stripped):
                item = re.sub(r"^•\s*", "- ", stripped)
                out.append(re.sub(r"^(\d+\.)\s+", r"\1 ", item))
            elif indented and out and _LIST_ITEM.match(out[-1].replace("- ", "• ", 1)):
                out[-1] = f"{out[-1]} {stripped}"  # wrapped list item
            else:
                out.append(stripped)
        flush_table()
        if page_no == 1:
            out.append("")

    md = "\n".join(out)
    md = re.sub(r"\n{3,}", "\n\n", md).strip() + "\n"
    header = (
        "<!-- Generated by scripts/extract_policies.py from data/raw/políticas_da_loja.pdf."
        " Do not edit by hand. -->\n\n"
    )
    return header + md


def write_policies_markdown(pdf_path: Path = POLICIES_PDF, md_path: Path = POLICIES_MD) -> Path:
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(pdf_to_markdown(pdf_path), encoding="utf-8", newline="\n")
    return md_path


def load_policies_markdown(md_path: Path = POLICIES_MD) -> str:
    return md_path.read_text(encoding="utf-8")
